/*
 * HIP test for V_SCREEN_PARTITION_4SE_B32 (VOP1 screen-partition table lookup),
 * pattern A.  Exercises base, DPP and SDWA encodings (vop1Helper -> variants
 * supported).
 *
 * gem5 (src/arch/amdgpu/common/insts/vop1.cc):
 *   D.u = screen_partition_table[ S0.u & 0xff ]   (256-entry LUT, values 0..0xf)
 *
 * The host reference embeds the exact same 256-entry table extracted from the
 * gem5 source, so the comparison is bit-exact.  Inputs sweep the low byte
 * 0..255 to cover the whole table.
 *
 * Variants exercised (probed with llvm-mc -mcpu=gfx950):
 *   base : v_screen_partition_4se_b32       vdst, vsrc
 *   dpp  : v_screen_partition_4se_b32_dpp   vdst, vsrc quad_perm:[1,0,3,2] ...
 *            -> src of lane^1
 *   sdwa : v_screen_partition_4se_b32_sdwa  vdst, vsrc dst_sel:DWORD src0_sel:DWORD
 *            -> like base
 *
 * Build: hipcc -O2 --offload-arch=gfx950 -o v_screen_partition_4se_b32 v_screen_partition_4se_b32.cpp
 */
